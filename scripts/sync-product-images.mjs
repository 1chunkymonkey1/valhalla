const args = new Set(process.argv.slice(2))
const missingOnly = args.has('--missing')
const ensureDirs = args.has('--ensure-dirs') || !missingOnly

function productPath(company, slug) {
  return `/images/products/${company}/${slug}.jpg`
}

function fileExists(company, slug) {
  return fs.existsSync(path.join(productsRoot, company, `${slug}.jpg`))
}

if (ensureDirs) {
  for (const hall of HALLS) {
    fs.mkdirSync(path.join(productsRoot, hall), { recursive: true })
  }
  fs.mkdirSync(path.join(productsRoot, '_plates'), { recursive: true })
}

const filled = {}
const missing = []
let filledCount = 0
let total = 0

for (const hall of HALLS) {
  filled[hall] = {}
  for (const slug of SLOTS[hall]) {
    total += 1
    if (fileExists(hall, slug)) {
      filled[hall][slug] = productPath(hall, slug)
      filledCount += 1
    } else {
      missing.push({ hall, slug, path: productPath(hall, slug) })
    }
  }
}

const banner = `/**
 * AUTO-GENERATED by scripts/sync-product-images.mjs — do not edit by hand.
 * Drop JPGs into public/images/products/{company}/{slug}.jpg then re-run:
 *   npm run sync:product-images
 *
 * Filled ${filledCount} / ${total} slots.
 */
`

const body = `export const PRODUCT_IMAGE_MANIFEST = ${JSON.stringify(filled, null, 2)}

/** Public URL if a still exists for this company + cell slug. */
export function productImageUrl(companyId, slug) {
  if (!companyId || !slug) return null
  return PRODUCT_IMAGE_MANIFEST[companyId]?.[slug] || null
}

/** Convention path (may 404 until the file is dropped). */
export function productImageConventionPath(companyId, slug) {
  if (!companyId || !slug) return null
  return \`/images/products/\${companyId}/\${slug}.jpg\`
}

export const PRODUCT_IMAGE_SLOTS = ${JSON.stringify(SLOTS, null, 2)}
`

if (!missingOnly) {
  fs.writeFileSync(outFile, banner + body, 'utf8')
  console.log(`Wrote ${path.relative(root, outFile)} (${filledCount}/${total} filled)`)
}

if (missingOnly || args.has('--report')) {
  console.log('\n## Missing product stills\n')
  console.log('| Hall | Slug | Drop path |')
  console.log('|------|------|-----------|')
  for (const m of missing) {
    console.log(`| ${m.hall} | ${m.slug} | \`public/images/products/${m.hall}/${m.slug}.jpg\` |`)
  }
  console.log(`\n${missing.length} remaining · ${filledCount} filled\n`)
} else {
  const priority01 = missing.filter((m) => m.slug.endsWith('-01'))
  console.log(`Remaining: ${missing.length}  |  Priority *-01 gaps: ${priority01.length}`)
  if (priority01.length) {
    console.log('Next *-01 drops:')
    for (const m of priority01.slice(0, 24)) {
      console.log(`  ${m.hall}/${m.slug}.jpg`)
    }
    if (priority01.length > 24) console.log(`  … +${priority01.length - 24} more`)
  }
}
