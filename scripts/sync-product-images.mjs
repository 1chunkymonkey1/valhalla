/**
 * Scan public/images/products/{company}/{slug}.jpg and write
 * src/data/productImageManifest.js so the UI can show photos when files exist.
 *
 * Usage:
 *   node scripts/sync-product-images.mjs
 *   node scripts/sync-product-images.mjs --missing
 *   node scripts/sync-product-images.mjs --ensure-dirs
 */

